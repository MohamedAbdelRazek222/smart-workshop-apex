end sw_pkg;
/

create or replace package body sw_pkg as

  function local_now return date is
  begin
    return cast(systimestamp at time zone 'Africa/Cairo' as date);
  end local_now;

  function to_text_query (p_text in varchar2) return varchar2 is
    l_clean varchar2(4000);
    l_word  varchar2(100);
    l_q     varchar2(4000);
    i       pls_integer := 1;
  begin
    l_clean := lower(regexp_replace(p_text, '[^[:alnum:] ]', ' '));
    loop
      l_word := regexp_substr(l_clean, '[^ ]+', 1, i);
      exit when l_word is null;
      if length(l_word) > 2
         and l_word not in ('the','and','when','with','from','car','has','have','there','not','for','after','while','very','some','its','this','that','are','was','customer','says')
      then
        l_q := l_q || case when l_q is not null then ' ACCUM ' end
                   || 'fuzzy({' || l_word || '}, 60, 50, weight)';
      end if;
      i := i + 1;
      exit when i > 25;
    end loop;
    return l_q;
  end to_text_query;

  function normalize_text (p_text in varchar2) return varchar2 is
    l     varchar2(4000);
    l_out varchar2(4000);
    w     varchar2(200);
    l_can sw_synonyms.canonical%type;
    i     pls_integer := 1;
  begin
    l := ' ' || lower(regexp_replace(nvl(p_text, ' '), '[^[:alnum:]/'' ]', ' ')) || ' ';
    l := regexp_replace(l, ' +', ' ');
    -- multi-word / punctuated terms first, longest first
    for s in (select term, canonical from sw_synonyms
              where regexp_like(term, '[ /'']') order by length(term) desc)
    loop
      l := replace(l, ' ' || s.term || ' ', ' ' || s.canonical || ' ');
    end loop;
    l := translate(l, '/''', '  ');
    loop
      w := regexp_substr(l, '[^ ]+', 1, i);
      exit when w is null;
      i := i + 1;
      select max(canonical) into l_can from sw_synonyms where term = w;
      if l_can is null and length(w) > 4 and w like '%s' and w not like '%ss' then
        w := substr(w, 1, length(w) - 1);                       -- light stemming
        select max(canonical) into l_can from sw_synonyms where term = w;
      end if;
      w := nvl(l_can, w);
      if length(w) >= 2 and w not in ('the','and','when','with','from','car','has','have','there','not','for',
           'after','while','very','some','its','this','that','are','was','customer','says','keep','keeps','is',
           'in','on','at','to','of','it','my','an','be','also','too','sometimes','especially','but','or','get','gets')
      then
        l_out := l_out || ' ' || w;
      end if;
    end loop;
    return trim(l_out);
  end normalize_text;

  function embed (p_text in varchar2) return vector is
    type t_arr is table of binary_double index by pls_integer;
    a      t_arr;
    l_norm varchar2(4000) := normalize_text(p_text);
    w      varchar2(200);
    prev   varchar2(200);
    g      varchar2(210);
    s      varchar2(4000);
    n      binary_double := 0;
    v      vector;
    i      pls_integer := 1;
    procedure add (p in varchar2, p_wgt in number) is
      k pls_integer := dbms_utility.get_hash_value(p, 1, c_dims);
    begin
      a(k) := case when a.exists(k) then a(k) else 0 end + p_wgt;
    end add;
  begin
    if l_norm is null then
      return null;
    end if;
    loop
      w := regexp_substr(l_norm, '[^ ]+', 1, i);
      exit when w is null;
      add('w:' || w, 3);                                       -- whole term
      g := '#' || w || '#';
      for j in 1 .. length(g) - 2 loop
        add('t:' || substr(g, j, 3), 1);                       -- char trigrams (typos, word forms)
      end loop;
      if prev is not null then
        add('b:' || prev || '_' || w, 1.5);                    -- word pairs
      end if;
      prev := w;
      i := i + 1;
    end loop;
    for k in 1 .. c_dims loop
      if a.exists(k) then n := n + a(k) * a(k); end if;
    end loop;
    n := sqrt(n);
    for k in 1 .. c_dims loop
      s := s || case when k > 1 then ',' end
             || case when a.exists(k)
                     then to_char(a(k) / n, 'FM0.00000', 'nls_numeric_characters=.,')
                     else '0' end;
    end loop;
    select to_vector('[' || s || ']', 256, float32) into v from dual;
    return v;
  end embed;

  function next_status (p_status in varchar2) return varchar2 is
  begin
    return case p_status
      when 'RECEIVED'      then 'DIAGNOSING'
      when 'DIAGNOSING'    then 'IN_PROGRESS'
      when 'WAITING_PARTS' then 'IN_PROGRESS'
      when 'IN_PROGRESS'   then 'QUALITY_CHECK'
      when 'QUALITY_CHECK' then 'READY'
      when 'READY'         then 'DELIVERED'
    end;
  end next_status;

  function status_label (p_status in varchar2) return varchar2 is
  begin
    return case p_status
      when 'RECEIVED'      then 'Vehicle received'
      when 'DIAGNOSING'    then 'Under diagnosis'
      when 'WAITING_PARTS' then 'Waiting for parts'
      when 'IN_PROGRESS'   then 'Repair in progress'
      when 'QUALITY_CHECK' then 'Quality check & road test'
      when 'READY'         then 'Ready for pickup'
      when 'DELIVERED'     then 'Delivered'
    end;
  end status_label;

  function status_pct (p_status in varchar2) return number is
  begin
    return case p_status
      when 'RECEIVED'      then 10
      when 'DIAGNOSING'    then 25
      when 'WAITING_PARTS' then 40
      when 'IN_PROGRESS'   then 60
      when 'QUALITY_CHECK' then 85
      when 'READY'         then 100
      when 'DELIVERED'     then 100
    end;
  end status_pct;

  procedure learn_from_job (p_vehicle_id in number, p_complaint in varchar2,
                            p_diagnosis in varchar2, p_work_done in varchar2) is
    l_model sw_vehicles.model%type;
    l_qv    vector;
    l_kb    number;
  begin
    if p_complaint is null or p_diagnosis is null or p_work_done is null then
      return;
    end if;
    select max(model) into l_model from sw_vehicles where vehicle_id = p_vehicle_id;
    l_qv := embed(p_complaint);
    -- same symptom + same root cause already known? count it, otherwise learn it
    select max(kb_id) keep (dense_rank first order by vector_distance(complaint_vec, l_qv, cosine))
    into   l_kb
    from   sw_repair_kb
    where  vector_distance(complaint_vec, l_qv, cosine) < 0.35
    and    utl_match.jaro_winkler_similarity(lower(root_cause), lower(p_diagnosis)) >= 85;

    if l_kb is not null then
      update sw_repair_kb set times_seen = times_seen + 1 where kb_id = l_kb;
    else
      insert into sw_repair_kb (model, complaint, root_cause, fix_action, times_seen, source_job)
      values (l_model, p_complaint, p_diagnosis, p_work_done, 1, 'Y');
    end if;
  end learn_from_job;

end sw_pkg;
/

