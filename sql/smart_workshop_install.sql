-- ---------- Customer feedback ----------
create table sw_feedback (
  feedback_id   number generated by default on null as identity primary key,
  job_card_id   number not null unique references sw_job_cards on delete cascade,
  rating        number(1) not null check (rating between 1 and 5),
  comments      varchar2(1000),
  created_at    date default cast(systimestamp at time zone 'Africa/Cairo' as date) not null
);

-- ---------- API used by the Kanban board and the public tracking page ----------
create or replace package sw_api as
  -- move a job card to another status (Kanban drag & drop)
  procedure set_status (p_job_card_id in number, p_status in varchar2);
  -- customer rating from the public tracking page (token = proof of ownership)
  procedure save_feedback (p_token in varchar2, p_rating in number, p_comments in varchar2);
end sw_api;
/

create or replace package body sw_api as

  procedure set_status (p_job_card_id in number, p_status in varchar2) is
  begin
    if p_status not in ('RECEIVED','DIAGNOSING','WAITING_PARTS','IN_PROGRESS','QUALITY_CHECK','READY','DELIVERED') then
      raise_application_error(-20001, 'Invalid status ' || p_status);
    end if;
    update sw_job_cards
    set    status = p_status
    where  job_card_id = p_job_card_id
    and    status <> p_status;
  end set_status;

  procedure save_feedback (p_token in varchar2, p_rating in number, p_comments in varchar2) is
    l_job sw_job_cards.job_card_id%type;
  begin
    select job_card_id into l_job
    from   sw_job_cards
    where  tracking_token = p_token
    and    status in ('READY','DELIVERED');

    merge into sw_feedback f
    using (select l_job job_card_id from dual) s
    on (f.job_card_id = s.job_card_id)
    when matched then update set f.rating = p_rating, f.comments = substr(p_comments, 1, 1000)
    when not matched then insert (job_card_id, rating, comments)
                          values (l_job, p_rating, substr(p_comments, 1, 1000));
  exception
    when no_data_found then
      raise_application_error(-20002, 'Rating is available once the car is ready.');
  end save_feedback;

end sw_api;
/

-- ---------- Service reminders: every 10,000 km or 6 months ----------
create or replace view sw_service_due_v as
with last_service as (
  select vehicle_id,
         max(mileage_in_km) keep (dense_rank last order by received_at) last_km,
         max(received_at) last_date
  from   sw_job_cards
  where  service_type = 'PERIODIC'
  group  by vehicle_id
)
select v.vehicle_id, v.plate_no, v.make, v.model, v.model_year, v.mileage_km,
       c.full_name customer_name, c.phone,
       ls.last_date,
       nvl(ls.last_km + 10000, ceil((nvl(v.mileage_km, 0) + 1) / 10000) * 10000) next_due_km,
       ls.last_date + 182 next_due_date,
       case
         when v.mileage_km >= nvl(ls.last_km + 10000, ceil((nvl(v.mileage_km, 0) + 1) / 10000) * 10000)
           or ls.last_date + 182 < sw_pkg.local_now                         then 'OVERDUE'
         when v.mileage_km >= nvl(ls.last_km + 10000, ceil((nvl(v.mileage_km, 0) + 1) / 10000) * 10000) - 1500
           or ls.last_date + 182 < sw_pkg.local_now + 30                    then 'DUE SOON'
         else 'OK'
       end due_status
from   sw_vehicles v
join   sw_customers c on c.customer_id = v.customer_id
left join last_service ls on ls.vehicle_id = v.vehicle_id;

