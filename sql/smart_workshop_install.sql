-- ---------- Package ----------
create or replace package sw_pkg as
  -- Turns free text ("engine shakes when cold") into an Oracle Text query
  function to_text_query (p_text in varchar2) return varchar2;
  -- Next status in the workflow
  function next_status (p_status in varchar2) return varchar2;
  -- Customer-friendly status label
  function status_label (p_status in varchar2) return varchar2;
  -- Progress percent for the customer tracking page
  function status_pct (p_status in varchar2) return number;
end sw_pkg;
/

create or replace package body sw_pkg as

  function to_text_query (p_text in varchar2) return varchar2 is
    l_clean varchar2(4000);
    l_word  varchar2(100);
    l_q     varchar2(4000);
    i       pls_integer := 1;
  begin
    l_clean := lower(regexp_replace(p_text, '[^[:alnum:] ]', ' '));
    loop
      l_word := regexp_substr(l_clean, '[^ ]+', 1, i);
      exit when l_word is null;
      if length(l_word) > 2
         and l_word not in ('the','and','when','with','from','car','has','have','there','not','for','after','while','very','some','its','this','that','are','was','customer','says')
      then
        l_q := l_q || case when l_q is not null then ' ACCUM ' end
                   || 'fuzzy({' || l_word || '}, 60, 50, weight)';
      end if;
      i := i + 1;
      exit when i > 25;
    end loop;
    return l_q;
  end to_text_query;

  function next_status (p_status in varchar2) return varchar2 is
  begin
    return case p_status
      when 'RECEIVED'      then 'DIAGNOSING'
      when 'DIAGNOSING'    then 'IN_PROGRESS'
      when 'WAITING_PARTS' then 'IN_PROGRESS'
      when 'IN_PROGRESS'   then 'QUALITY_CHECK'
      when 'QUALITY_CHECK' then 'READY'
      when 'READY'         then 'DELIVERED'
    end;
  end next_status;

  function status_label (p_status in varchar2) return varchar2 is
  begin
    return case p_status
      when 'RECEIVED'      then 'Vehicle received'
      when 'DIAGNOSING'    then 'Under diagnosis'
      when 'WAITING_PARTS' then 'Waiting for parts'
      when 'IN_PROGRESS'   then 'Repair in progress'
      when 'QUALITY_CHECK' then 'Quality check & road test'
      when 'READY'         then 'Ready for pickup'
      when 'DELIVERED'     then 'Delivered'
    end;
  end status_label;

  function status_pct (p_status in varchar2) return number is
  begin
    return case p_status
      when 'RECEIVED'      then 10
      when 'DIAGNOSING'    then 25
      when 'WAITING_PARTS' then 40
      when 'IN_PROGRESS'   then 60
      when 'QUALITY_CHECK' then 85
      when 'READY'         then 100
      when 'DELIVERED'     then 100
    end;
  end status_pct;

end sw_pkg;
/

-- ---------- Views ----------
create or replace view sw_job_cards_v as
select j.job_card_id, j.job_no, j.status,
       sw_pkg.status_label(j.status) status_label,
       sw_pkg.status_pct(j.status)   status_pct,
       j.service_type, j.customer_complaint, j.diagnosis, j.work_done,
       j.estimated_cost, j.mileage_in_km, j.received_at, j.promised_at, j.delivered_at,
       j.tracking_token,
       case when j.status not in ('READY','DELIVERED') and j.promised_at < sysdate then 'Y' else 'N' end late_yn,
       v.vehicle_id, v.plate_no, v.make, v.model, v.model_year,
       c.customer_id, c.full_name customer_name, c.phone,
       t.technician_id, t.full_name technician_name
from   sw_job_cards j
join   sw_vehicles  v on v.vehicle_id  = j.vehicle_id
join   sw_customers c on c.customer_id = v.customer_id
left join sw_technicians t on t.technician_id = j.technician_id;
