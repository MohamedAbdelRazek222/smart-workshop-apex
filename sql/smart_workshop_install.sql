-- ---------- Tables ----------
create table sw_customers (
  customer_id   number generated by default on null as identity primary key,
  full_name     varchar2(100) not null,
  phone         varchar2(30)  not null,
  email         varchar2(120),
  created_at    date default sysdate not null
);

create table sw_vehicles (
  vehicle_id    number generated by default on null as identity primary key,
  customer_id   number not null references sw_customers,
  plate_no      varchar2(20)  not null unique,
  vin           varchar2(17),
  make          varchar2(40)  default 'KIA' not null,
  model         varchar2(40)  not null,
  model_year    number(4),
  mileage_km    number
);

create table sw_technicians (
  technician_id number generated by default on null as identity primary key,
  full_name     varchar2(100) not null,
  specialty     varchar2(40)  not null,
  active_yn     varchar2(1) default 'Y' not null check (active_yn in ('Y','N'))
);

create table sw_job_cards (
  job_card_id     number generated by default on null as identity primary key,
  job_no          varchar2(20) unique,
  vehicle_id      number not null references sw_vehicles,
  technician_id   number references sw_technicians,
  service_type    varchar2(30) default 'REPAIR' not null
                  check (service_type in ('PERIODIC','REPAIR','WARRANTY','BODY')),
  customer_complaint varchar2(1000) not null,
  diagnosis       varchar2(1000),
  work_done       varchar2(1000),
  status          varchar2(20) default 'RECEIVED' not null
                  check (status in ('RECEIVED','DIAGNOSING','WAITING_PARTS','IN_PROGRESS','QUALITY_CHECK','READY','DELIVERED')),
  mileage_in_km   number,
  estimated_cost  number(10,2),
  promised_at     date,
  received_at     date default sysdate not null,
  delivered_at    date,
  tracking_token  varchar2(32)
);

create table sw_job_status_log (
  log_id        number generated by default on null as identity primary key,
  job_card_id   number not null references sw_job_cards on delete cascade,
  status        varchar2(20) not null,
  changed_at    date default sysdate not null,
  changed_by    varchar2(100)
);

-- Knowledge base of solved repairs (the "workshop memory")
create table sw_repair_kb (
  kb_id         number generated by default on null as identity primary key,
  model         varchar2(40),
  complaint     varchar2(1000) not null,
  root_cause    varchar2(1000) not null,
  fix_action    varchar2(1000) not null,
  parts         varchar2(400),
  labor_hours   number(5,2),
  times_seen    number default 1 not null
);

-- ---------- Triggers ----------
create or replace trigger sw_job_cards_biu
before insert or update on sw_job_cards
for each row
begin
  if inserting then
    :new.job_no         := nvl(:new.job_no, 'JC-' || to_char(sysdate,'YY') || '-' || lpad(:new.job_card_id, 5, '0'));
    if :new.tracking_token is null then
      -- unguessable public tracking token
      select lower(substr(rawtohex(standard_hash(sys_guid() || dbms_random.string('X', 40) || systimestamp, 'SHA256')), 1, 32))
      into   :new.tracking_token
      from   dual;
    end if;
  end if;
  if :new.status = 'DELIVERED' and :new.delivered_at is null then
    :new.delivered_at := sysdate;
  end if;
end;
/

create or replace trigger sw_job_cards_aiu
after insert or update of status on sw_job_cards
for each row
begin
  if inserting or :old.status <> :new.status then
    insert into sw_job_status_log (job_card_id, status, changed_by)
    values (:new.job_card_id, :new.status,
            coalesce(sys_context('APEX$SESSION','APP_USER'), user));
  end if;
end;
